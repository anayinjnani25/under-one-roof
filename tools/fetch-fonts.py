"""Download the site's fonts from Google Fonts once and host them in assets/fonts/.

Writes assets/css/fonts.css (Latin faces, loaded everywhere) and
assets/css/fonts-te.css / fonts-hi.css (Telugu / Devanagari, loaded only for that language).
All fonts are under the SIL Open Font License, which allows self-hosting.
Re-run only to change fonts:  python tools/fetch-fonts.py
"""
import pathlib, re, urllib.request

root = pathlib.Path(__file__).resolve().parent.parent
fonts = root / 'assets' / 'fonts'
fonts.mkdir(parents=True, exist_ok=True)
UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'
seen = {}  # one file per distinct download (variable fonts come back once per weight)

def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=30).read()

def build(families, out_name, subsets):
    css = get('https://fonts.googleapis.com/css2?' + '&'.join('family=' + f for f in families) + '&display=swap').decode()
    blocks, out = re.findall(r'/\* ([\w-]+) \*/\s*(@font-face \{.*?\})', css, re.S), []
    for subset, block in blocks:
        if subset not in subsets:
            continue
        fam = re.search(r"font-family: '([^']+)'", block).group(1)
        style = re.search(r'font-style: (\w+)', block).group(1)
        weight = re.search(r'font-weight: ([\d ]+)', block).group(1).replace(' ', '-')
        url = re.search(r'url\((https://[^)]+\.woff2)\)', block).group(1)
        name = seen.get(url) or f"{fam.lower().replace(' ', '-')}-{weight}{'-italic' if style == 'italic' else ''}-{subset}.woff2"
        if url not in seen:
            seen[url] = name
            (fonts / name).write_bytes(get(url))
        out.append(block.replace(url, '../fonts/' + name))
    (root / 'assets' / 'css' / out_name).write_text('/* generated by tools/fetch-fonts.py */\n' + '\n'.join(out) + '\n', encoding='utf-8')
    print(out_name, len(out), 'faces')

build(['Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500',
       'Fraunces:ital,opsz,wght@0,9..144,300..700;1,9..144,300..700',
       'Pinyon+Script', 'Special+Elite', 'Lato:wght@400'], 'fonts.css', {'latin', 'latin-ext'})  # Lato: the logo's lettering
build(['Noto+Serif+Telugu:wght@400;500;600'], 'fonts-te.css', {'telugu'})
build(['Noto+Serif+Devanagari:wght@400;500;600'], 'fonts-hi.css', {'devanagari'})
