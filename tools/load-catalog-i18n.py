"""Turn supabase/catalog-i18n.json into SQL that fills the i18n columns.

    python tools/load-catalog-i18n.py > supabase/catalog-i18n.sql

Run the SQL in the Supabase SQL editor (or via the dashboard) after editing the JSON.
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((root / 'supabase' / 'catalog-i18n.json').read_text(encoding='utf-8'))


def lit(value):
    return "'" + json.dumps(value, ensure_ascii=False).replace("'", "''") + "'::jsonb"


out = ['-- Generated by tools/load-catalog-i18n.py from supabase/catalog-i18n.json']
for slug, langs in data['categories'].items():
    out.append(f"update public.categories set i18n = {lit(langs)} where slug = '{slug}';")
for pid, langs in data['products'].items():
    out.append(f"update public.products set i18n = {lit(langs)} where id = '{pid}';")
sys.stdout.reconfigure(encoding='utf-8')
print('\n'.join(out))
